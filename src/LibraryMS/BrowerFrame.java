    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        // TODO add your handling code here:

        try {
            int dialogueResult=JOptionPane.showConfirmDialog(rootPane, "Do you really Want to remove this borrowing","Warning",JOptionPane.YES_NO_OPTION);
            if(dialogueResult ==JOptionPane.YES_OPTION){
                String id= Id.getText();
                insert=con.prepareStatement("delete from borrowing  where bookid=? ");
                insert.setString(1,id);
                insert.executeUpdate();

                JOptionPane.showMessageDialog(rootPane, "Borrowing Removed Successfully!");
                BorrowerData();
            }
        } catch (SQLException ex) {
            Logger.getLogger(BrowerFrame.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_DeleteBtnActionPerformed

    private void UpdateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateBtnActionPerformed
        // TODO add your handling code here:

        try {
            String id= Id.getText();
            String name= Name.getText();
            String email= Book.getText();
            //String gender= genderBox.getSelectedItem().toString();
            
            insert=con.prepareStatement("update borrowing set studentname=?,book=?,date_borrowed=?,date_return=? where bookid=? ");
            insert.setString(1,name);
            insert.setString(2,email);
            SimpleDateFormat sdf=new SimpleDateFormat("yyyy-MM-dd");
            String date_borrowed=sdf.format(dateb.getDate());
            String date_return=sdf.format(dater.getDate());
            
            insert.setString(3, date_borrowed);
             insert.setString(4, date_return);
            insert.setString(5,id);

            insert.executeUpdate();
            JOptionPane.showMessageDialog(rootPane, "Borrowing Updated Successfully");
            BorrowerData();
            Id.setText("");
            Name.setText("");
            Book.setText("");
            //Address.setText("");

        } catch (SQLException ex) {
            Logger.getLogger(BrowerFrame.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_UpdateBtnActionPerformed

