 private void BorrowerData(){
    try {
        insert = con.prepareStatement("SELECT * FROM borrowing");
        ResultSet Rs = insert.executeQuery();
        ResultSetMetaData Rsmd = Rs.getMetaData();
        int data = Rsmd.getColumnCount();

        DefaultTableModel Def = (DefaultTableModel) table1.getModel();
        Def.setRowCount(0); // Clear table before inserting new data
        
        while (Rs.next()) {
            Vector v2 = new Vector();
             for (int a=1;a<data;a++){
            
            v2.add(Rs.getString("bookid"));
            v2.add(Rs.getString("studentname"));
            v2.add(Rs.getString("book"));
            v2.add(Rs.getString("date_borrowed"));
            v2.add(Rs.getString("date_return"));
             }
            Def.addRow(v2);
        }
    } catch (SQLException ex) {
        Logger.getLogger(BrowerFrame.class.getName()).log(Level.SEVERE, null, ex);
    }
}

